/*
    IMPLEMENTATION OF THE SCD WITH TRIGGERS
        -I WILL CREATE A BEFORE UPDATE TRIGGER ON THE SOURCE TABLE
            -> checks if any tracked columns are changing
            -> if column changes, expires the current record of that employee and inserts a new version
*/
 -- CREATE TRIGGER ---
CREATE OR REPLACE TRIGGER trg_scd2_employees
BEFORE UPDATE ON src_employees          -- before update trigger on source table
FOR EACH ROW
DECLARE
    v_changed BOOLEAN := FALSE;
BEGIN
    -- Step 1: Detect change in tracked columns (on deparmtent, salary and name)
    IF :NEW.department != :OLD.department OR :NEW.salary != :OLD.salary OR :NEW.full_name != :OLD.full_name THEN
       v_changed := TRUE;   --flag that activates when changes are made
    END IF;

    IF v_changed THEN
        -- Step 2: Expire current record in dim_employees
        UPDATE dim_employees
        SET end_date = SYSDATE,
            current_flag = 'N'
        WHERE emp_id = :OLD.emp_id
          AND current_flag = 'Y';

        -- Step 3: Insert new version into dim_employees
        INSERT INTO dim_employees (emp_id, full_name, department, salary,start_date, end_date, current_flag)
        VALUES (:NEW.emp_id, :NEW.full_name, :NEW.department, :NEW.salary,SYSDATE, NULL, 'Y');
    END IF;
END;
/

