-- ============================
-- ========== STEP 1 ============
--Detect changed records by comparing the source table with the dimension records on the flag
-- We will store only the changed employees in the view

CREATE OR REPLACE VIEW view_scd2_changed_employees AS
SELECT s.*
FROM src_employees s
JOIN dim_employees d
  ON s.emp_id = d.emp_id
WHERE d.current_flag = 'Y'
  AND (
       s.full_name   <> d.full_name OR
       s.department  <> d.department OR
       s.salary      <> d.salary
      );
      
CREATE GLOBAL TEMPORARY TABLE tmp_changed_employees (
    emp_id        NUMBER,
    full_name     VARCHAR2(100),
    department    VARCHAR2(100),
    salary        NUMBER
) ON COMMIT PRESERVE ROWS;

-- Step: Insert view result into temp table
INSERT INTO tmp_changed_employees
SELECT emp_id, full_name, department, salary
FROM view_scd2_changed_employees;

SELECT * FROM view_scd2_changed_employees;
SELECT * FROM src_employees;
SELECT * FROM dim_employees;
-- ============================
-- ========== STEP 2 ============
-- we will update the dimension table because we need to expire the current records if changes happen
BEGIN
    UPDATE dim_employees d
    SET end_date = SYSDATE, current_flag = 'N'
    WHERE d.current_flag = 'Y'
    AND EXISTS (
        SELECT 1 FROM tmp_changed_employees t
        WHERE t.emp_id = d.emp_id
    );
      COMMIT;
END;

-- ============================
-- ========== STEP 3 ============
--insert new versions into dim_employees
BEGIN
    INSERT INTO dim_employees (emp_id, full_name, department, salary,start_date, end_date, current_flag)
    SELECT s.emp_id, s.full_name, s.department, s.salary,SYSDATE, NULL, 'Y'
    FROM tmp_changed_employees s;
    COMMIT;
END;
SELECT * FROM view_scd2_changed_employees;

-- ============================
-- ========== STEP 4 ============
--handle new employees -> inserts employees that don't exist yet in dimension table
BEGIN
    INSERT INTO dim_employees (emp_id, full_name, department, salary,start_date, end_date, current_flag)
    SELECT s.emp_id, s.full_name, s.department, s.salary,SYSDATE, NULL, 'Y'
    FROM src_employees s
    WHERE NOT EXISTS (
        SELECT 1 FROM dim_employees d
        WHERE d.emp_id = s.emp_id
    );
    COMMIT;
END;

