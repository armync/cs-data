/*
    What is SCD2:
    SCD2 allows you to track historical changes in dimension (aka history) records.
    Allows programmers to maintain and view the full history of changes.
    
    *Those descriptions are made based on my implementation and serve as an example*
    
    1. SCD2 with Triggers
        - create a BEFORE UPDATE trigger on the source table which will record into the history table the new values
        - updates the current row and marks it as EXPIRED
        Advantages:
        - easy to implement 
        - process is automatic because of the triggers
        - works well with OLTP logic and systems
        Cons:
        - performance decreases - runs on every change
        - complex to maintain as logic grows
        - prone to errors in big applications
    2. SCD2 with CDC (Change Data Capture)
        - the DB captures change logs using internal mechanisms( like logs, flashbacks, implicit triggers)
        - ETL tools mark the changes and apply the logic downstream
        Advantages:
        - near real-time actions
        - lightweight for the system
        - good for streaming into data lakes ( Snowflake, BigQuery...)
        Cons:
        - complex setup and implementation
        - may require extra licenses and tools
        - dev still needs to apply SCD2 logic separatly downstream
    3. SCD2 with ETL (Extract, Transform, Load model)
        - can run on schedule
        - pull full or partial data from sources
        Advantages:
        - best approach for data warehouse or reporting
        - easy to control logic with SQL or related tools (ODI, Talend..)
        - very easy to scale
        Cons:
        - no real-time
        - requires good design for large volumes and transactions( partitioning, bulk loads, etc..)
        - needs data gouveranance to avoid duplicates
        
    Summary:
        USE WITH TRIGGERS WHEN -> work on small oltp app trakers with few changes
        USE WITH CDC WHEN -> work with real-time sync or Kafka/DL pipelines
        USE WITH ETL ->  work with batch-based historycal tracking for BI apps 
*/

